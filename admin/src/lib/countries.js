export function countryName(code) {
  return COUNTRIES[code]?.[0] || code || "Unknown";
}

export function countryCentroid(code) {
  const row = COUNTRIES[code];
  return row ? { lon: row[1], lat: row[2] } : null;
}

/* Regional-indicator flag from an ISO alpha-2 code — no image assets needed. */
export function flagEmoji(code) {
  if (!code || code.length !== 2) return "🌐";
  const base = 0x1f1e6;
  const chars = code.toUpperCase().split("").map((c) => base + (c.charCodeAt(0) - 65));
  if (chars.some((c) => c < base || c > base + 25)) return "🌐";
  return String.fromCodePoint(...chars);
}

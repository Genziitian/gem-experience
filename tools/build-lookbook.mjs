/* Builds the Lookbook at /lookbook/ from the catalog's editorial photographs.
 *
 * Every image here is already on the site: the `models` list on each High
 * Jewellery piece and on each Fine Jewellery collection. The page is written
 * as static HTML rather than assembled in the browser so it needs no catalog
 * download and reads complete to search engines. Re-run after the catalog
 * changes; `npm run build:seo` runs it first.
 *
 *   node tools/build-lookbook.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WEB = path.join(ROOT, "frontend");

function readAssigned(file, global) {
  const t = fs.readFileSync(file, "utf8");
  const start = t.indexOf("{", t.indexOf(`window.${global}`));
  return JSON.parse(t.slice(start, t.lastIndexOf("}") + 1));
}

const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

const hj = readAssigned(path.join(WEB, "high-jewellery/data.js"), "HJ_DATA");
const fj = readAssigned(path.join(WEB, "fine-jewellery/data.js"), "FJ_DATA");

/* A Fine Jewellery collection is shown only once it has photographed pieces
   in the shop, the same rule the shop's own menu follows. */
const fjLive = new Set(fj.products.filter((p) => p.images && p.images.length).map((p) => p.collection));

const exists = (rel) => fs.existsSync(path.join(WEB, rel));

const chapters = [];

chapters.push({
  id: "high-jewellery",
  title: "High Jewellery",
  lede: "One of a kind, photographed as worn.",
  groups: hj.products
    .filter((p) => (p.models || []).length)
    .map((p) => ({
      name: p.name,
      note: p.materials,
      href: p.storyUrl || `/high-jewellery/#/product/${p.id}`,
      cta: p.storyUrl ? `Read the story of ${p.name}` : `View ${p.name}`,
      images: p.models.map((m) => `/high-jewellery/${m}`).filter((src) => exists(src)),
    }))
    .filter((g) => g.images.length),
});

chapters.push({
  id: "fine-jewellery",
  title: "Fine Jewellery",
  lede: "The collections, worn.",
  groups: fj.collections
    .filter((c) => fjLive.has(c.name) && (c.models || []).length)
    .map((c) => ({
      name: c.name,
      note: c.lede,
      href: `/fine-jewellery/#/${c.id}`,
      cta: `Enter ${c.name}`,
      images: c.models.map((m) => `/fine-jewellery/${m}`).filter((src) => exists(src)),
    }))
    .filter((g) => g.images.length),
});

const total = chapters.reduce((n, c) => n + c.groups.reduce((m, g) => m + g.images.length, 0), 0);

const group = (g) => `      <section class="lb-group" aria-label="${esc(g.name)}">
        <header class="lb-group-head">
          <h3 class="lb-group-title">${esc(g.name)}</h3>
          ${g.note ? `<p class="lb-group-note">${esc(g.note)}</p>` : ""}
          <a class="hs-link" href="${esc(g.href)}">${esc(g.cta)}</a>
        </header>
        <div class="lb-grid">
${g.images.map((src, i) => `          <a class="lb-shot" href="${esc(g.href)}"><img src="${esc(src)}" alt="${esc(g.name)}, image ${i + 1}" loading="lazy" decoding="async"></a>`).join("\n")}
        </div>
      </section>`;

const body = chapters.map((c) => `    <section class="lb-chapter" id="${c.id}" aria-labelledby="lb-${c.id}-h">
      <div class="lb-chapter-head">
        <h2 class="pg-section-title" id="lb-${c.id}-h">${esc(c.title)}</h2>
        <p class="pg-note">${esc(c.lede)}</p>
      </div>
${c.groups.map(group).join("\n")}
    </section>`).join("\n\n");

const nav = chapters.map((c) => `<a class="lb-jump" href="#${c.id}">${esc(c.title)}</a>`).join("");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Lookbook — Gem Experience</title>
<meta name="description" content="The Gem Experience lookbook: High Jewellery and Fine Jewellery in tanzanite and the coloured stones of East Africa, photographed as worn.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="preload" as="style" href="https://fonts.googleapis.com/css2?family=EB+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500&family=Jost:wght@300;400;500;700&display=swap" onload="this.onload=null;this.rel='stylesheet'">
<noscript><link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=EB+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500&family=Jost:wght@300;400;500;700&display=swap"></noscript>
<link rel="stylesheet" href="../css/pages.css">
<link rel="stylesheet" href="../css/site-nav.css">
<link rel="stylesheet" href="../css/mini-cart.css">
<link rel="stylesheet" href="../css/gift-note.css" media="print" onload="this.media='all'">
</head>
<body class="pg">
<!-- Generated by tools/build-lookbook.mjs from the catalog. Edit the catalog, not this file. -->
<div class="pg-wrap">
  <div id="pg-header"></div>
  <header class="pg-hero">
    <span class="pg-kicker">The House</span>
    <h1 class="pg-title">Lookbook</h1>
    <p class="pg-lede">The pieces as they are meant to be seen: worn. ${total} photographs from the house's shoots.</p>
    <nav class="lb-jumps" aria-label="Chapters">${nav}</nav>
  </header>

  <main class="pg-main lb">
${body}
  </main>

  <div id="pg-footer"></div>
</div>
<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.118.0/dist/umd/supabase.js"></script>
<script src="../js/config.js"></script>
<script src="../js/gem.js"></script>
<script src="../js/site-footer.js"></script>
<script src="../js/site-content.js"></script>
<script src="../js/site-nav.js"></script>
<script src="../js/mini-cart.js"></script>
<script src="../js/gift-note.js"></script>
<script src="../js/shell.js"></script>
<script>GemShell.mount();</script>
<script src="../js/analytics.js" defer></script>
</body>
</html>
`;

fs.mkdirSync(path.join(WEB, "lookbook"), { recursive: true });
fs.writeFileSync(path.join(WEB, "lookbook/index.html"), html);
console.log(`lookbook: ${total} photographs in ${chapters.reduce((n, c) => n + c.groups.length, 0)} groups`);
